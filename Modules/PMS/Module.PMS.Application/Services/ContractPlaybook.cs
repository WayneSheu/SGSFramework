    private static IReadOnlyList<PlaybookIndustryDto> Industries() =>
        Enum.GetValues<ContractIndustry>().Where(i => i != ContractIndustry.General).Select(industry => new PlaybookIndustryDto(
            industry switch
            {
                ContractIndustry.Finance => "金融業（銀行、證券、保險、金控）",
                ContractIndustry.Medical => "醫療業（醫院、診所、生技醫療）",
                _ => "製造業（工廠自動化、MES、ERP 整合）"
            },
            ContractComplianceCatalog.For(industry).Select(s => new ComplianceGuideDto(s.Name, s.Risk, s.Defense)).ToList())).ToList();
